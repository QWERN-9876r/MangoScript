// The class of `queue T`. Its values are a ring in an array: `shift()` and `unshift()` move the
// start instead of the other values, as they do in an array. A full ring is copied into one twice
// its size, and one that is mostly empty into one half its size, so each operation costs a few
// steps on average. The fields are data, so a copy for another thread keeps the queue, and the
// thread that gets it gives it back its class (thread-helpers.ts).

export type QueueHelper = 'queue';

export const QUEUE_HELPERS: Readonly<Record<QueueHelper, readonly string[]>> = {
  queue: [
    'class $$Queue {',
    '  constructor(items = []) {',
    '    this.$$queue = [...items];',
    '    this.$$start = 0;',
    '    this.$$length = this.$$queue.length;',
    '  }',
    '',
    '  get length() {',
    '    return this.$$length;',
    '  }',
    '',
    '  push(...items) {',
    '    for (const item of items) {',
    '      if (this.$$length === this.$$queue.length) this.$$resize();',
    '      this.$$queue[(this.$$start + this.$$length++) % this.$$queue.length] = item;',
    '    }',
    '    return this.$$length;',
    '  }',
    '',
    '  unshift(...items) {',
    '    for (let i = items.length - 1; i >= 0; i--) {',
    '      if (this.$$length === this.$$queue.length) this.$$resize();',
    '      this.$$start = (this.$$start || this.$$queue.length) - 1;',
    '      this.$$queue[this.$$start] = items[i];',
    '      this.$$length++;',
    '    }',
    '    return this.$$length;',
    '  }',
    '',
    '  // An empty queue gives null; a value that is taken out is not held any more.',
    '  shift() {',
    '    if (this.$$length === 0) return null;',
    '    const item = this.$$queue[this.$$start];',
    '    this.$$queue[this.$$start] = undefined;',
    '    this.$$start = (this.$$start + 1) % this.$$queue.length;',
    '    this.$$length--;',
    '    this.$$shrink();',
    '    return item;',
    '  }',
    '',
    '  pop() {',
    '    if (this.$$length === 0) return null;',
    '    const at = (this.$$start + --this.$$length) % this.$$queue.length;',
    '    const item = this.$$queue[at];',
    '    this.$$queue[at] = undefined;',
    '    this.$$shrink();',
    '    return item;',
    '  }',
    '',
    '  // A position from the start, or from the end if it is negative, as with an array.',
    '  at(index) {',
    '    const i = Math.trunc(index) || 0;',
    '    const at = i < 0 ? i + this.$$length : i;',
    '    if (at < 0 || at >= this.$$length) return null;',
    '    return this.$$queue[(this.$$start + at) % this.$$queue.length];',
    '  }',
    '',
    '  clear() {',
    '    this.$$queue = [];',
    '    this.$$start = 0;',
    '    this.$$length = 0;',
    '  }',
    '',
    '  *[Symbol.iterator]() {',
    '    for (let i = 0; i < this.$$length; i++) {',
    '      yield this.$$queue[(this.$$start + i) % this.$$queue.length];',
    '    }',
    '  }',
    '',
    '  // Removes a value, for the channels: at the start it costs a step, elsewhere the whole queue.',
    '  $$delete(item) {',
    '    if (this.$$length > 0 && this.$$queue[this.$$start] === item) return this.shift();',
    '    const items = [...this];',
    '    const at = items.indexOf(item);',
    '    if (at >= 0) this.$$keep((_, i) => i !== at);',
    '  }',
    '',
    '  // Keeps the values that pass the test, in their order.',
    '  $$keep(test) {',
    '    const items = [...this].filter(test);',
    '    this.$$queue = items;',
    '    this.$$start = 0;',
    '    this.$$length = items.length;',
    '    this.$$shrink();',
    '  }',
    '',
    '  // The values from the start of a new ring with room for as many again, and at least 8.',
    '  $$resize() {',
    '    const items = [...this];',
    '    items.length = Math.max(8, this.$$length * 2);',
    '    this.$$queue = items;',
    '    this.$$start = 0;',
    '  }',
    '',
    '  $$shrink() {',
    '    if (this.$$queue.length > 8 && this.$$length * 4 <= this.$$queue.length) this.$$resize();',
    '  }',
    '}',
  ],
};
