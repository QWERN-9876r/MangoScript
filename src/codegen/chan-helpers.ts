// The helpers of channels. A channel is data, `{ $$chan: id, size, zero }`, so it is copied to
// workers like any value. What it holds and who waits for it live in the main thread, in a
// registry that the modules of the program share; a worker asks the main thread through the pool
// (go-helpers.ts). Receiving from a closed channel gives the zero value of its type, as in Go.

export type ChanHelper = 'chan' | 'chanWorker';

/** Receives values until the channel is closed: `for v in ch`; the same in both threads. */
const RANGE = [
  'async function* $$range(channel) {',
  '  while (true) {',
  '    const [value, ok] = await $$receive(channel, true);',
  '    if (!ok) return;',
  '    yield value;',
  '  }',
  '}',
];

export const CHAN_HELPERS: Readonly<Record<ChanHelper, readonly string[]>> = {
  /** The main thread: the registry, sending, receiving and closing. */
  chan: [
    'const $$channels = Symbol.for("mangoscript.channels");',
    '',
    'function $$registry() {',
    '  return (globalThis[$$channels] ??= { next: 0, states: new Map() });',
    '}',
    '',
    'function $$chan(size, zero) {',
    '  return { $$chan: String($$registry().next++), size, zero };',
    '}',
    '',
    'function $$state(channel) {',
    '  const { states } = $$registry();',
    '  let state = states.get(channel.$$chan);',
    '  if (!state) {',
    '    state = { buffer: [], receivers: [], senders: [], closed: false };',
    '    states.set(channel.$$chan, state);',
    '  }',
    '  return state;',
    '}',
    '',
    'function $$send(channel, value) {',
    '  const state = $$state(channel);',
    '  if (state.closed) return Promise.reject(new Error("send on a closed channel"));',
    '  if ($$deliver(state, value)) return Promise.resolve();',
    '  if (state.buffer.length < channel.size) {',
    '    state.buffer.push(value);',
    '    return Promise.resolve();',
    '  }',
    '  return new Promise((resolve, reject) => state.senders.push({ value, resolve, reject }));',
    '}',
    '',
    '// Gives a value to a receiver that still waits: one of a select that has gone on refuses it.',
    'function $$deliver(state, value) {',
    '  while (state.receivers.length > 0) {',
    '    if (state.receivers.shift()([value, true])) return true;',
    '  }',
    '  return false;',
    '}',
    '',
    '// The first sender that still waits, which a select may have left.',
    'function $$sender(state) {',
    '  while (state.senders.length > 0) {',
    '    const sender = state.senders.shift();',
    '    if (sender.claim?.() ?? true) return sender;',
    '  }',
    '  return null;',
    '}',
    '',
    '// What can be received at once: from the buffer, from a sender, or the zero value after close.',
    'function $$take(channel, state) {',
    '  if (state.buffer.length > 0) {',
    '    const value = state.buffer.shift();',
    '    const sender = $$sender(state);',
    '    if (sender) {',
    '      state.buffer.push(sender.value);',
    '      sender.resolve();',
    '    }',
    '    return [value, true];',
    '  }',
    '  const sender = $$sender(state);',
    '  if (sender) {',
    '    sender.resolve();',
    '    return [sender.value, true];',
    '  }',
    '  return state.closed ? [$$zero(channel), false] : null;',
    '}',
    '',
    'function $$receive(channel, withOk = false) {',
    '  const state = $$state(channel);',
    '  const ready = $$take(channel, state);',
    '  const received = ready',
    '    ? Promise.resolve(ready)',
    '    : new Promise((resolve) => state.receivers.push((result) => (resolve(result), true)));',
    '  return withOk ? received : received.then(([value]) => value);',
    '}',
    '',
    'function $$zero(channel) {',
    '  return Array.isArray(channel.zero) ? [] : channel.zero;',
    '}',
    '',
    'function $$close(channel) {',
    '  const state = $$state(channel);',
    '  if (state.closed) throw new Error("close of a closed channel");',
    '  state.closed = true;',
    '  for (const receiver of state.receivers.splice(0)) receiver([$$zero(channel), false]);',
    '  for (const sender of state.senders.splice(0)) {',
    '    if (sender.claim?.() ?? true) sender.reject(new Error("send on a closed channel"));',
    '  }',
    '}',
    '',
    '// `select`: the index of the case that went on, and what it received. A case is { channel }',
    '// to receive or { channel, value } to send. One that can go on at once wins, a random one as',
    '// in Go; else `default`, -1, if there is one; else the first that can go on later.',
    'function $$select(cases, hasDefault) {',
    '  const order = cases.map((_, i) => i).sort(() => Math.random() - 0.5);',
    '  for (const i of order) {',
    '    const { channel } = cases[i];',
    '    const state = $$state(channel);',
    '    if (!("value" in cases[i])) {',
    '      const ready = $$take(channel, state);',
    '      if (ready) return Promise.resolve([i, ...ready]);',
    '    } else if (state.closed) {',
    '      return Promise.reject(new Error("send on a closed channel"));',
    '    } else if ($$deliver(state, cases[i].value)) {',
    '      return Promise.resolve([i]);',
    '    } else if (state.buffer.length < channel.size) {',
    '      state.buffer.push(cases[i].value);',
    '      return Promise.resolve([i]);',
    '    }',
    '  }',
    '  if (hasDefault) return Promise.resolve([-1]);',
    '  return new Promise((resolve, reject) => {',
    '    let done = false;',
    '    const claim = () => !done && (done = true);',
    '    cases.forEach(({ channel, ...send }, i) => {',
    '      const state = $$state(channel);',
    '      if ("value" in send) {',
    '        state.senders.push({ value: send.value, claim, resolve: () => resolve([i]), reject });',
    '      } else {',
    '        state.receivers.push((result) => claim() && (resolve([i, ...result]), true));',
    '      }',
    '    });',
    '  });',
    '}',
    '',
    ...RANGE,
  ],
  /** A worker: each operation is a request to the main thread ($$ask, in the `serve` helper). */
  chanWorker: [
    'const $$workerKey = Math.random().toString(36).slice(2);',
    'let $$channelCount = 0;',
    '',
    'function $$chan(size, zero) {',
    '  return { $$chan: `${$$workerKey}.${$$channelCount++}`, size, zero };',
    '}',
    '',
    'function $$send(channel, value) {',
    '  return $$ask("send", channel, value);',
    '}',
    '',
    'function $$receive(channel, withOk = false) {',
    '  return $$ask("receive", channel).then((result) => (withOk ? result : result[0]));',
    '}',
    '',
    'function $$select(cases, hasDefault) {',
    '  return $$ask("select", cases, hasDefault);',
    '}',
    '',
    '// An error, such as a second close, fails the worker, as a panic fails a Go program.',
    'function $$close(channel) {',
    '  $$ask("close", channel).catch((error) => {',
    '    setTimeout(() => {',
    '      throw error;',
    '    });',
    '  });',
    '}',
    '',
    ...RANGE,
  ],
};
